"""SSH access to the machines through the bastion, and the first-boot checks.

Every function is pure: it builds texts and :class:`~finkfat_ops.runner.Command` values,
or interprets outputs.

ff-ops writes its own ``.state/ssh_config`` (the explorer is reached directly on its
floating IP, the other machines through it with ``ProxyJump``) and its own
``.state/known_hosts``. Each machine is recorded under a stable alias
(``HostKeyAlias``), so that the host key of a recreated VM is forgotten by alias
(:func:`forget_host_command`) without touching the operator's ``~/.ssh/known_hosts``.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from ipaddress import IPv4Address
from pathlib import Path

from finkfat_ops.checks import Finding, Level
from finkfat_ops.config import InfraConfig
from finkfat_ops.heat.servers import server_id_output
from finkfat_ops.naming import Role, ssh_host_alias
from finkfat_ops.runner import Command, CommandResult

CLOUD_INIT_TIMEOUT_S = 1800.0
"""Longest wait for cloud-init to finish (package installation included)."""


def ssh_config_path(state_dir: Path) -> Path:
    """Return the location of the generated ``ssh_config``."""
    return state_dir / "ssh_config"


def known_hosts_path(state_dir: Path) -> Path:
    """Return the location of ff-ops' own ``known_hosts``."""
    return state_dir / "known_hosts"


def build_ssh_config(
    infra: InfraConfig,
    bastion_ip: IPv4Address,
    known_hosts: Path,
    identity_file: str | None,
) -> str:
    """Build the ``ssh_config`` of the enabled machines.

    Parameters
    ----------
    infra : InfraConfig
        Versioned structure (roles, fixed IPs, SSH user).
    bastion_ip : IPv4Address
        Public address of the explorer.
    known_hosts : Path
        ff-ops' own ``known_hosts`` file.
    identity_file : str | None
        Private key to use; ``None`` leaves the choice to ``ssh``.

    Returns
    -------
    str
        The file content, one ``Host`` block per enabled role.
    """
    bastion = ssh_host_alias(Role.EXPLORER)
    lines = ["# Generated by ff-ops from the servers stack. Do not edit.", ""]
    for role, cfg in infra.roles.items():
        if not cfg.enabled:
            continue
        alias = ssh_host_alias(role)
        lines += [
            f"Host {alias}",
            f"    HostName {bastion_ip if role == Role.EXPLORER else cfg.fixed_ip}",
            f"    User {infra.ssh_user}",
            f"    HostKeyAlias {alias}",
            f"    UserKnownHostsFile {known_hosts}",
            "    StrictHostKeyChecking accept-new",
            "    ServerAliveInterval 30",
        ]
        if identity_file:
            lines += [f"    IdentityFile {identity_file}", "    IdentitiesOnly yes"]
        if role != Role.EXPLORER:
            lines.append(f"    ProxyJump {bastion}")
        lines.append("")
    return "\n".join(lines)


def recreated_roles(
    infra: InfraConfig, before: dict[str, object] | None, after: dict[str, object]
) -> list[Role]:
    """List the roles whose VM is new or was replaced, by comparing VM IDs (pure).

    Parameters
    ----------
    infra : InfraConfig
        Versioned structure.
    before : dict[str, object] | None
        Outputs of the servers stack before the apply; ``None`` if it did not exist.
    after : dict[str, object]
        Outputs after the apply.

    Returns
    -------
    list[Role]
        Roles whose ``server_<role>_id`` output changed (their old host key is obsolete).
    """
    previous = before or {}
    recreated = []
    for role, _ in infra.roles.items():
        current = after.get(server_id_output(role))
        if current and current != previous.get(server_id_output(role)):
            recreated.append(role)
    return recreated


def ssh_command(
    config: Path, role: Role, remote: Sequence[str] = (), *, timeout_s: float | None = None
) -> Command:
    """Build ``ssh -F <config> ffat-<role> [command]``.

    Parameters
    ----------
    config : Path
        Generated ``ssh_config``.
    role : Role
        Target machine.
    remote : Sequence[str]
        Command to run remotely; empty for an interactive shell.
    timeout_s : float | None
        Seconds before the command is killed; ``None`` waits forever.

    Returns
    -------
    Command
        Interactive when ``remote`` is empty; otherwise captured, in batch mode (it fails
        instead of asking for a password or a passphrase) and without SSH's own warnings
        (``LogLevel=ERROR``), so that the output is the remote command's.
    """
    # -F: ff-ops' own ssh_config, which knows the alias ffat-<role>, the bastion
    # (ProxyJump) and the key. Batch options only for a remote command: a script must fail
    # rather than wait for a passphrase nobody will type.
    batch = ("-o", "BatchMode=yes", "-o", "LogLevel=ERROR") if remote else ()
    argv = ("ssh", "-F", str(config), *batch, ssh_host_alias(role), *remote)
    return Command(argv=argv, timeout_s=timeout_s, interactive=not remote)


def forget_host_command(known_hosts: Path, role: Role) -> Command:
    """``ssh-keygen -R ffat-<role>``: forget the host key of a recreated VM."""
    return Command.of("ssh-keygen", "-f", str(known_hosts), "-R", ssh_host_alias(role))


# -------------------------------------------------------------------- first-boot checks


@dataclass(frozen=True)
class RemoteCheck:
    """A check run on a machine over SSH.

    Attributes
    ----------
    label : str
        What is checked, e.g. ``"docker running"``.
    command : tuple[str, ...]
        Remote command; the check passes when it exits with status 0.
    fix : str
        What to do when it fails.
    timeout_s : float
        Seconds before the check is abandoned.
    warning_codes : tuple[int, ...]
        Exit statuses meaning "done, with something to look at" rather than a failure.
    """

    label: str
    command: tuple[str, ...]
    fix: str
    timeout_s: float = 60.0
    warning_codes: tuple[int, ...] = ()


CLOUD_INIT_RECOVERABLE = 2
"""Exit status of ``cloud-init status`` when it finished with recoverable errors."""

DETAIL_MAX_CHARS = 400
"""Longest detail of a failed check shown to the operator."""


def init_checks(infra: InfraConfig, role: Role) -> list[RemoteCheck]:
    """List the first-boot checks of a role, in order.

    cloud-init is waited for first; the other checks only make sense once it is done.

    Parameters
    ----------
    infra : InfraConfig
        Versioned structure.
    role : Role
        The machine.

    Returns
    -------
    list[RemoteCheck]
        cloud-init finished, Docker running, data volume mounted (if any), clock synchronised.
    """
    logs = "read /var/log/cloud-init-output.log on the machine (ff-ops ssh {role})"
    checks = [
        RemoteCheck(
            "cloud-init finished without error",
            # sudo: cloud-init reads /run/cloud-init/cloud.cfg, readable by root only.
            ("sudo", "cloud-init", "status", "--wait", "--long"),
            logs.format(role=role),
            CLOUD_INIT_TIMEOUT_S,
            warning_codes=(CLOUD_INIT_RECOVERABLE,),
        ),
        RemoteCheck(
            "docker running",
            ("systemctl", "is-active", "--quiet", "docker"),
            "check `systemctl status docker` on the machine",
        ),
    ]
    volume = infra.roles.of(role).volume
    if volume is not None:
        checks.append(
            RemoteCheck(
                f"data volume mounted on {volume.mount}",
                ("mountpoint", "-q", volume.mount),
                f"check /usr/local/sbin/ffat-mount-volume in {logs.format(role=role)}",
            )
        )
    checks.append(
        RemoteCheck(
            "clock synchronised",
            ("timedatectl", "show", "--property=NTPSynchronized", "--value"),
            "check `chronyc sources` on the machine (it may take a minute after boot)",
        )
    )
    return checks


def evaluate_check(check: RemoteCheck, result: CommandResult) -> Finding:
    """Turn the result of a remote check into a finding (pure).

    The clock check passes on the output ``yes``; the others on exit status 0. An exit
    status listed in ``check.warning_codes`` gives a warning, with the command's output.

    Parameters
    ----------
    check : RemoteCheck
        The check.
    result : CommandResult
        Result of its SSH command.

    Returns
    -------
    Finding
        OK, WARN or ERROR; WARN and ERROR carry the output and the check's fix.
    """
    passed = result.ok
    if check.command[0] == "timedatectl":
        passed = passed and result.stdout.strip() == "yes"
    if passed:
        return Finding(Level.OK, check.label)
    detail = _detail(result)
    if result.returncode in check.warning_codes:
        return Finding(Level.WARN, f"{check.label}: done with warnings{detail}", check.fix)
    return Finding(Level.ERROR, f"{check.label}: failed{detail}", check.fix)


def _detail(result: CommandResult) -> str:
    """Summarise a command's output (stdout first) on one line, keeping its end if too long."""
    lines = [line.strip() for line in f"{result.stdout}\n{result.stderr}".splitlines()]
    text = " | ".join(line for line in lines if line)
    if not text:
        return f" (exit status {result.returncode})"
    if len(text) > DETAIL_MAX_CHARS:
        text = "…" + text[-DETAIL_MAX_CHARS:]  # the end holds the conclusion (error, status)
    return f" (exit status {result.returncode}: {text})"


PGADMIN_PORT = 5050
"""Port of pgAdmin, published on the explorer's loopback and forwarded by the tunnel."""


def tunnel_command(config: Path, local_port: int = PGADMIN_PORT) -> Command:
    """Forward ``localhost:<local_port>`` to pgAdmin on the explorer (pure).

    Returns
    -------
    Command
        ``ssh -N -L <port>:127.0.0.1:5050 ffat-explorer``, interactive: it runs until the
        operator stops it (Ctrl-C).
    """
    forward = f"{local_port}:127.0.0.1:{PGADMIN_PORT}"
    argv = ("ssh", "-F", str(config), "-N", "-L", forward, ssh_host_alias(Role.EXPLORER))
    return Command(argv=argv, timeout_s=None, interactive=True)
