"""Serialisation of generated Heat templates and cloud-init documents."""

from __future__ import annotations

from typing import Any

import yaml

HEADER = "# Generated by ff-ops from infra.yaml and infra.local.yaml. Do not edit.\n"


class _ReadableDumper(yaml.SafeDumper):
    """Safe YAML dumper writing multi-line strings as literal blocks (``|``)."""


def _represent_str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    """Represent multi-line strings in the literal block style.

    PyYAML falls back to a quoted string by itself when a value cannot be written that
    way (e.g. trailing spaces).
    """
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_ReadableDumper.add_representer(str, _represent_str)


def dump_yaml(document: Any) -> str:
    """Serialise ``document`` as readable YAML: key order kept, multi-line text as blocks.

    Parameters
    ----------
    document : Any
        Plain data (dicts, lists, strings, numbers, booleans).

    Returns
    -------
    str
        YAML text, equivalent to ``yaml.safe_dump`` once loaded back.
    """
    return yaml.dump(
        document,
        Dumper=_ReadableDumper,
        sort_keys=False,
        default_flow_style=False,
        width=100,
        allow_unicode=True,
    )


def render_template(template: dict[str, Any]) -> str:
    """Render a HOT template as YAML, keeping the key order of ``template``.

    Parameters
    ----------
    template : dict[str, Any]
        Template built by one of the ``finkfat_ops.heat`` modules.

    Returns
    -------
    str
        YAML text, preceded by a "generated, do not edit" comment.
    """
    return HEADER + dump_yaml(template)
